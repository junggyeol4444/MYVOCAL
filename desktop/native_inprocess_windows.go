package main

// Experimental WebView2 internal transport: http://127.0.0.1:58319 remains
// the Chromium origin for IndexedDB compatibility, but the host serves requests
// directly via WebResourceRequested without binding a TCP port.
// Enabled only with MYVOCAL_NATIVE_INPROCESS=1 until real GUI QA is complete.
import (
 "errors"
 "fmt"
 "net/http"
 "sort"
 "strings"
 "syscall"
 "unsafe"
 "runtime"
 "log"
)

var nativeShlwapi=syscall.NewLazyDLL("shlwapi.dll")
var procSHCreateMemStream=nativeShlwapi.NewProc("SHCreateMemStream")

func nativeGetRequestString(object unsafe.Pointer,index uintptr)(string,error){
 var raw unsafe.Pointer
 hr:=nativeCOMCall(object,index,nativeCOMPointer(unsafe.Pointer(&raw)))
 if !comSucceeded(hr){return "",fmt.Errorf("WebView2 request string HRESULT 0x%08x",uint32(hr))}
 return nativeCOMUTF16(raw),nil
}
func nativeGetHeader(object unsafe.Pointer,name string)string{
 if object==nil{return ""}
 label,e:=syscall.UTF16PtrFromString(name)
 if e!=nil{return ""}
 var raw unsafe.Pointer
 hr:=nativeCOMCall(object,3,nativeCOMPointer(unsafe.Pointer(label)),nativeCOMPointer(unsafe.Pointer(&raw)))
 if !comSucceeded(hr){return ""}
 return nativeCOMUTF16(raw)
}
func nativeRequestBody(stream unsafe.Pointer)([]byte,error){
 if stream==nil{return nil,nil}
 defer nativeCOMCall(stream,2)
 var body []byte
 buffer:=make([]byte,32*1024)
 for{
  var n uint32
  hr:=nativeCOMCall(stream,3,nativeCOMPointer(unsafe.Pointer(&buffer[0])),nativeCOMValue(uintptr(len(buffer))),nativeCOMPointer(unsafe.Pointer(&n)))
  if !comSucceeded(hr){return nil,fmt.Errorf("WebView2 request stream read failed 0x%08x",uint32(hr))}
  if n>uint32(len(buffer)){return nil,errors.New("WebView2 request returned invalid byte count")}
  if len(body)+int(n)>nativeInprocessMaxRequestBytes{return nil,errors.New("WebView2 request exceeded 16MiB")}
  if n>0{body=append(body,buffer[:n]...)}
  if n==0||hr==1{return body,nil}
 }
}
func nativeResponseHeaders(h http.Header,bodyLen int)string{
 // Header values are generated by our own handler, but prevent CR/LF
 // injection from reaching the WebView2 raw header parser.
 names:=make([]string,0,len(h))
 for k:=range h{names=append(names,k)}
 sort.Strings(names)
 var result strings.Builder
 for _,k:=range names{
  if strings.ContainsAny(k,"\r\n:")||strings.EqualFold(k,"Content-Length"){continue}
  for _,v:=range h[k]{
   if strings.ContainsAny(v,"\r\n"){continue}
   result.WriteString(k);result.WriteString(": ");result.WriteString(v);result.WriteString("\r\n")
  }
 }
 result.WriteString(fmt.Sprintf("Content-Length: %d\r\n",bodyLen))
 return result.String()
}
func nativeResponseStream(bytes []byte)(unsafe.Pointer,error){
 if len(bytes)==0{return nil,nil}
 p,_,e:=procSHCreateMemStream.Call(uintptr(unsafe.Pointer(&bytes[0])),uintptr(len(bytes)))
 runtime.KeepAlive(bytes)
 if p==0{return nil,fmt.Errorf("SHCreateMemStream failed: %v",e)}
 // The Windows ABI returned a pointer-sized COM interface value. Interpret
 // the slot as a pointer rather than converting a uintptr into a Go address.
 // The IStream is native-owned and must be released with IUnknown.Release.
 return *(*unsafe.Pointer)(unsafe.Pointer(&p)),nil
}
func nativeWriteWebResponse(state *nativeWebViewState,args unsafe.Pointer,status int,header http.Header,body []byte)error{
 if state==nil||state.Environment==nil{return errors.New("WebView2 environment absent")}
 stream,err:=nativeResponseStream(body)
 if err!=nil{return err}
 if stream!=nil{defer nativeCOMCall(stream,2)}
 reason,_:=syscall.UTF16PtrFromString(http.StatusText(status))
 rawHeaders,_:=syscall.UTF16PtrFromString(nativeResponseHeaders(header,len(body)))
 var response unsafe.Pointer
 hr:=nativeCOMCall(state.Environment,4,
  nativeCOMPointer(stream),
  nativeCOMValue(uintptr(status)),
  nativeCOMPointer(unsafe.Pointer(reason)),
  nativeCOMPointer(unsafe.Pointer(rawHeaders)),
  nativeCOMPointer(unsafe.Pointer(&response)))
 if !comSucceeded(hr)||response==nil{return fmt.Errorf("CreateWebResourceResponse failed 0x%08x",uint32(hr))}
 defer nativeCOMCall(response,2)
 hr=nativeCOMCall(args,5,nativeCOMPointer(response))
 if !comSucceeded(hr){return fmt.Errorf("WebView2 put_Response failed 0x%08x",uint32(hr))}
 return nil
}
// Native COM event arguments and deferrals are owned by the WebView2 STA.
// Only the handler's pure-Go request processing runs on a worker. This avoids
// blocking the WebView2 message pump during local image/voice/video generation.
const nativeMaxPendingResources=8

type nativePendingResource struct {
 args unsafe.Pointer
 deferral unsafe.Pointer
}
type nativeResourceResult struct{
 id uint64
 result inprocessResponse
 err error
}

// Called only on the owning STA, including during shutdown.
func nativeCompleteResource(state *nativeWebViewState, pending nativePendingResource, result inprocessResponse, workErr error) {
 if !state.Shutdown && state.Environment!=nil {
  if workErr!=nil {
   result=inprocessResponse{Status:http.StatusInternalServerError,Header:http.Header{"Content-Type":[]string{"text/plain; charset=utf-8"}},Body:[]byte("MYVOCAL in-process request failed")}
  }
  if err:=nativeWriteWebResponse(state,pending.args,result.Status,result.Header,result.Body);err!=nil {
   // We must complete the deferral even if building a response failed.
   // Never attempt a network fallback, because direct mode has no listener.
   log.Printf("WebView2 resource response error: %v",err)
  }
 }
 nativeCOMCall(pending.deferral,3) // ICoreWebView2Deferral.Complete
 nativeCOMCall(pending.deferral,2) // IUnknown.Release
 nativeCOMCall(pending.args,2)     // event args retained by AddRef
}
func nativeDrainResourceQueue(state *nativeWebViewState){
 if state==nil||state.ResourceReady==nil{return}
 for{
  select{
  case result:=<-state.ResourceReady:
   pending,ok:=state.ResourcePending[result.id]
   if !ok {continue} // completed on shutdown or duplicate message
   delete(state.ResourcePending,result.id)
   nativeCompleteResource(state,pending,result.result,result.err)
  default:return
  }
 }
}
func nativeAbortPendingResources(state *nativeWebViewState){
 if state==nil{return}
 for id,pending:=range state.ResourcePending{
  delete(state.ResourcePending,id)
  nativeCompleteResource(state,pending,inprocessResponse{},errors.New("window closed"))
 }
 // Go-only worker results may still arrive, but cannot access any COM object.
}

func nativeWebResourceRequested(this *comHandler,sender,args unsafe.Pointer)uintptr{
 state:=nativeCallbackOwner(this)
 if state==nil{return 0x80004003}
 if !nativeOnOwnerSTA(state){return rpcEWrongThread}
 if state!=nativeActive||state.Shutdown||state.Life.isClosing()||args==nil||state.RequestHandler==nil{
  return 0x80004003
 }
 var request unsafe.Pointer
 hr:=nativeCOMCall(args,3,nativeCOMPointer(unsafe.Pointer(&request)))
 if !comSucceeded(hr)||request==nil{return 0x80004005}
 defer nativeCOMCall(request,2)
 uri,err:=nativeGetRequestString(request,3)
 if err!=nil{return 0x80004005}
 method,err:=nativeGetRequestString(request,5)
 if err!=nil{return 0x80004005}
 var headersCOM unsafe.Pointer
 hr=nativeCOMCall(request,9,nativeCOMPointer(unsafe.Pointer(&headersCOM)))
 if !comSucceeded(hr){return 0x80004005}
 if headersCOM!=nil{defer nativeCOMCall(headersCOM,2)}
 headers:=make(http.Header)
 for _,name:=range []string{"Origin","X-MYVOCAL-Session","X-MYVOCAL-Instance","Content-Type","Accept"}{
  if value:=nativeGetHeader(headersCOM,name);value!=""{headers.Set(name,value)}
 }
 var content unsafe.Pointer
 hr=nativeCOMCall(request,7,nativeCOMPointer(unsafe.Pointer(&content)))
 if !comSucceeded(hr){return 0x80004005}
 payload,readErr:=nativeRequestBody(content)
 if state.ResourceReady==nil{return 0x80004005}
 // WebView2 requires a deferral if processing outlives this STA callback.
 // Limit in-flight requests so unresponsive local engines cannot exhaust RAM.
 var deferral unsafe.Pointer
 hr=nativeCOMCall(args,6,nativeCOMPointer(unsafe.Pointer(&deferral)))
 if !comSucceeded(hr)||deferral==nil{return 0x80004005}
 nativeCOMCall(args,1) // retain event args until its deferral completes on STA
 state.ResourceNext++
 id:=state.ResourceNext
 state.ResourcePending[id]=nativePendingResource{args:args,deferral:deferral}
 if readErr!=nil || len(state.ResourcePending)>nativeMaxPendingResources {
  code:=http.StatusRequestEntityTooLarge
  if readErr==nil{code=http.StatusServiceUnavailable}
  nativeDrainResourceQueue(state)
  pending:=state.ResourcePending[id]
  delete(state.ResourcePending,id)
  nativeCompleteResource(state,pending,inprocessResponse{Status:code,Header:http.Header{"Content-Type":[]string{"text/plain; charset=utf-8"}},Body:[]byte(http.StatusText(code))},nil)
  return 0
 }
 handler:=state.RequestHandler
 go func(){
  result,dispatchErr:=dispatchInprocessRequest(handler,method,uri,headers,payload)
  // This buffered channel is exclusively drained on the owning STA. At most
  // nativeMaxPendingResources workers can be active at one time.
  state.ResourceReady<-nativeResourceResult{id:id,result:result,err:dispatchErr}
  nativePostSTAEvent(state,wmNativeResourceReady)
 }()
 return 0
}
func nativeRegisterResourceInterceptor(state *nativeWebViewState)error{
 if state==nil||state.WebView==nil||state.RequestHandler==nil{return errors.New("invalid in-process WebView2 state")}
 filter,_:=syscall.UTF16PtrFromString(fixedOrigin+"/*")
 // Filter WebResourceContext ALL = 0; all document/fetch/XHR requests are local.
 hr:=nativeCOMCall(state.WebView,57,nativeCOMPointer(unsafe.Pointer(filter)),nativeCOMValue(0))
 if !comSucceeded(hr){return fmt.Errorf("WebResourceRequested filter failed 0x%08x",uint32(hr))}
 state.ResourceHandler=newCOMHandler(iidResourceHandler,syscall.NewCallback(nativeWebResourceRequested),state)
 hr=nativeCOMCall(state.WebView,55,nativeCOMPointer(unsafe.Pointer(state.ResourceHandler)),nativeCOMPointer(unsafe.Pointer(&state.ResourceToken)))
 if !comSucceeded(hr){return fmt.Errorf("WebResourceRequested registration failed 0x%08x",uint32(hr))}
 state.ResourceSubscribed=true
 return nil
}
